def main():
    try:
        conn = sqlite3.connect(DB_NAME)
        c = conn.cursor()

        # اطمینان از وجود جدول با ستون‌های جدید
        c.execute("""
        CREATE TABLE IF NOT EXISTS activities(
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT,
            category TEXT,
            time_slot TEXT,
            field TEXT,
            mission_type TEXT,
            importance INTEGER,
            points INTEGER,
            requires_proof INTEGER DEFAULT 1,
            active INTEGER DEFAULT 1
        )
        """)

        # پاک کردن فعالیت‌های قبلی (اگر نمی‌خواهی پاک شود این دو خط را حذف کن)
        c.execute("DELETE FROM activities")

        for title, category, time_slot, field, mission_type, importance, points, requires_proof in activities:
            c.execute(
                """
                INSERT INTO activities
                (title, category, time_slot, field, mission_type, importance, points, requires_proof, active)
                VALUES (?,?,?,?,?,?,?,?,1)
                """,
                (title, category, time_slot, field, mission_type, importance, points, requires_proof),
            )

        conn.commit()
        conn.close()
        print(f"{len(activities)} فعالیت با موفقیت اضافه شد ✅")

    except Exception as e:
        print("❌ خطا در پر کردن دیتابیس:", e)


if __name__ == "__main__":
    main()
